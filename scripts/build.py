"""Build dist/CameraBusinessUse.exe (one file, ExifTool inside). Run with the Windows venv Python:

    .venv-win/Scripts/python.exe scripts/build.py [--deploy DIR]

ExifTool goes in as a single zip (exiftool-<version>.zip at the bundle root); the app
unpacks it once to <exe folder>/.data/exiftool-<version>/. A onefile exe unpacks its whole
payload to %TEMP% on every launch, so the payload is kept small: see DROP.
"""
import argparse
import shutil
import subprocess
import sys
from pathlib import Path

import fetch_exiftool

ROOT = Path(__file__).resolve().parent.parent
NAME = "CameraBusinessUse"
ICON = ROOT / "assets" / "icon.ico"
WORK = ROOT / "build" / "pyinstaller"

# Qt files a QtWidgets-only app never loads (software OpenGL, Qt's own translations, QtNetwork).
# Matched against lower-cased bundle paths. Using QtNetwork later means removing it here and in the spec.
DROP = ["opengl32sw.dll", "translations", "qt6network.dll", "qtuiotouchplugin"]

# PyInstaller's command line cannot remove collected files, so the spec is generated here.
SPEC = """\
# Generated by scripts/build.py; edit that instead.
a = Analysis([{entry!r}], pathex=[{root!r}], excludes=["PySide6.QtNetwork"],
             datas=[({exiftool!r}, "."), ({icon!r}, "assets")])
keep = lambda toc: [e for e in toc if not any(d in e[0].lower() for d in {drop!r})]
exe = EXE(PYZ(a.pure), a.scripts, keep(a.binaries), keep(a.datas),
          name={name!r}, icon={icon!r}, console=False, upx=False)
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--deploy", metavar="DIR", help="also copy the exe to this folder (a local Windows folder to run it from)")
    parser.add_argument("--entry", default=str(ROOT / "main.py"), help="script to freeze (default: main.py)")
    args = parser.parse_args()
    if sys.platform != "win32":
        sys.exit("Run this with the Windows venv Python: .venv-win/Scripts/python.exe scripts/build.py")

    WORK.mkdir(parents=True, exist_ok=True)
    exiftool = shutil.make_archive(str(WORK / f"exiftool-{fetch_exiftool.VERSION}"), "zip", fetch_exiftool.ensure("win"))
    spec = WORK / f"{NAME}.spec"
    spec.write_text(SPEC.format(entry=str(Path(args.entry).resolve()), root=str(ROOT), exiftool=exiftool,
                                icon=str(ICON), drop=DROP, name=NAME))
    subprocess.check_call([sys.executable, "-m", "PyInstaller", "--noconfirm",
                           "--distpath", str(ROOT / "dist"), "--workpath", str(WORK), str(spec)])
    exe = ROOT / "dist" / f"{NAME}.exe"
    print(f"built {exe} ({exe.stat().st_size / 1e6:.0f} MB)")
    if args.deploy:
        Path(args.deploy).mkdir(parents=True, exist_ok=True)
        print("copied to", shutil.copy2(exe, args.deploy))


if __name__ == "__main__":
    main()
